"""Run the live evaluation harness and generate docs/evaluation_report.md."""
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
os.environ.setdefault("ADR_JWT_SECRET", "evaluation-only-secret")

from app.database import get_conn
from app.evaluation import error_analysis, run_evaluation, sensitivity_experiment
from app.retrieval import build_index
from app.seed import generate

METRICS = (
    "authority_selection_accuracy", "answer_accuracy", "citation_accuracy",
    "access_control_accuracy", "conflict_detection_accuracy",
    "manual_override_success", "rollback_success",
)


def _fmt(value):
    return "n/a" if value is None else f"{value:.2f}%" if isinstance(value, (float, int)) else str(value)


def _ensure_dataset():
    conn = get_conn()
    if conn.execute("SELECT COUNT(*) FROM eval_queries").fetchone()[0] == 0:
        generate()
    build_index()
    return {
        "documents": conn.execute("SELECT COUNT(*) FROM documents").fetchone()[0],
        "versions": conn.execute("SELECT COUNT(*) FROM versions").fetchone()[0],
        "approvals": conn.execute("SELECT COUNT(*) FROM approvals").fetchone()[0],
        "owners": conn.execute("SELECT COUNT(*) FROM owners").fetchone()[0],
        "queries": conn.execute("SELECT COUNT(*) FROM eval_queries").fetchone()[0],
    }


def _metric_table(baseline, proposed):
    lines = ["| Metric | Baseline | Proposed | Improvement |", "|---|---:|---:|---:|"]
    for metric in METRICS:
        before = baseline.get(metric)
        after = proposed.get(metric)
        delta = round(after - before, 2) if isinstance(before, (int, float)) and isinstance(after, (int, float)) else None
        lines.append(f"| {metric} | {_fmt(before)} | {_fmt(after)} | {_fmt(delta) if delta is not None else 'n/a'} |")
    return "\n".join(lines)


def _scenario_table(baseline, proposed):
    names = sorted(set(baseline.get("scenario_metrics", {})) | set(proposed.get("scenario_metrics", {})))
    lines = ["| Scenario type | Baseline authority | Proposed authority |", "|---|---:|---:|"]
    for name in names:
        before = baseline.get("scenario_metrics", {}).get(name, {}).get("authority_selection_accuracy")
        after = proposed.get("scenario_metrics", {}).get(name, {}).get("authority_selection_accuracy")
        lines.append(f"| {name} | {_fmt(before)} | {_fmt(after)} |")
    return "\n".join(lines)


def main():
    stats = _ensure_dataset()
    baseline = run_evaluation("baseline")
    proposed = run_evaluation("proposed")
    analysis = error_analysis()
    sensitivity = sensitivity_experiment()
    report = f"""# Evaluation Report

_Generated by `scripts/run_evaluation.py` from the live SQLite database._

## Setup and dataset

The harness runs retrieval, access filtering, resolver selection, and grounded
answer generation for every planted query. Evaluation state is copied to a
temporary SQLite database, so override and rollback checks cannot alter the live
authority state. Dataset counts: {json.dumps(stats, sort_keys=True)}.

## Baseline vs Proposed

{_metric_table(baseline, proposed)}

## Per-scenario authority accuracy

{_scenario_table(baseline, proposed)}

## Error analysis

The proposed run assigns one category to every failed query. Counts and up to
three concrete examples are returned by `GET /api/eval/error-analysis`.

```json
{json.dumps(analysis, indent=2)}
```

## Weight sensitivity

```json
{json.dumps(sensitivity, indent=2)}
```

## Limitations

TF-IDF retrieval and the offline answer provider are intentionally lightweight.
The planted dataset is deterministic but synthetic, so stakeholder review and
representative production documents remain necessary. A resolver metric can
also expose retrieval weaknesses; that is reported as an error rather than
silently hidden.

## Why deterministic authority scoring

Approval status, ownership authority, conflicts, and version lifecycle are
structured governance facts. A deterministic resolver makes the selected source
reproducible, explainable, and auditable. The AI layer receives only the one
selected version and may summarize it, but it never decides authority.
"""
    output = ROOT / "docs" / "evaluation_report.md"
    output.write_text(report, encoding="utf-8")
    print(_metric_table(baseline, proposed))
    print(f"Generated {output}")


if __name__ == "__main__":
    main()
